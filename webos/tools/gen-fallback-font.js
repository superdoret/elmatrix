// Generates js/fallbackfont.js from assets/fonts/tom-thumb.bdf (ASCII + Spanish accents only).
// Usage: node tools/gen-fallback-font.js
const fs = require('fs');
const path = require('path');
const src = fs.readFileSync(path.join(__dirname, '../assets/fonts/tom-thumb.bdf'), 'utf8').split(/\r?\n/);
const keep = new Set([0x20, 0x21].concat(Array.from({ length: 95 }, (_, i) => 32 + i)));
'áéíóúüñÁÉÍÓÚÜÑ¿¡°'.split('').forEach(c => keep.add(c.charCodeAt(0)));
const header = [], body = [];
let cur = null, inHeader = true;
for (const line of src) {
  if (line.startsWith('STARTCHAR')) { inHeader = false; cur = [line]; continue; }
  if (inHeader) { if (!line.startsWith('CHARS') && !line.startsWith('COMMENT')) header.push(line); continue; }
  if (cur) {
    cur.push(line);
    if (line.startsWith('ENDCHAR')) {
      const enc = parseInt(cur.find(l => l.startsWith('ENCODING')).split(' ')[1], 10);
      if (keep.has(enc)) body.push(cur.join('\n'));
      cur = null;
    }
  }
}
const text = header.join('\n') + '\nCHARS ' + body.length + '\n' + body.join('\n') + '\nENDFONT\n';
const out = "/* Generated by tools/gen-fallback-font.js from tom-thumb.bdf (MIT). Used only if the BDF files cannot be loaded. */\n" +
  "window.ELM = window.ELM || {};\nwindow.ELM.fallbackFontText = " + JSON.stringify(text) + ";\n";
fs.writeFileSync(path.join(__dirname, '../js/fallbackfont.js'), out);
console.log('fallbackfont.js', out.length, 'bytes,', body.length, 'glyphs');
